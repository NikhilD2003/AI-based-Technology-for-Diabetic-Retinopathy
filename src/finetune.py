"""Domain adaptation: continue training the APTOS model on IDRiD, test on IDRiD's official 103 test images.

    py -3.10 src/finetune.py

Each fine-tuned model is compared with the exact checkpoint it started from, on the same images.
Everything is written to results/finetune/; the original results are not touched.
"""
import numpy as np
import pandas as pd
import torch

from analyze import N_BOOT, boot_ci, delong, mcnemar, md, metrics, qwk
from data import CACHE, ROOT
from train import BASE, SEEDS, run

OUT = ROOT / "results/finetune"
# fixed before the first run and not tuned afterwards: a 5x lower learning rate than pre-training
FINETUNE = {**BASE, "source": "idrid", "lr": 1e-4, "epochs": 15}


def train_all():
    t = pd.read_csv(ROOT / "results/images.csv")
    caches = {"graham": torch.from_numpy(np.load(CACHE / "graham.npy")).cuda()}
    where = dict(preds=OUT / "preds", models=OUT / "models", keep=True)
    for seed in SEEDS:
        # the first run saved weights for seed 0 only, so the starting models are retrained here
        run("base", seed, t, caches, cfg=dict(BASE), **where)
        run("finetuned", seed, t, caches, cfg=FINETUNE, init=OUT / f"models/base_s{seed}.pt", **where)


def report():
    t = pd.read_csv(ROOT / "results/images.csv")
    y = t.diagnosis.values
    evals = {"idrid_test": ((t.dataset == "idrid") & (t.split == "test")).values,
             "aptos_test": ((t.dataset == "aptos") & (t.split == "test")).values}
    probs = {n: [np.load(OUT / f"preds/{n}_s{s}.npz")["probs"] for s in SEEDS] for n in ("base", "finetuned")}
    per_seed = pd.DataFrame([dict(model=n, eval=e, seed=s, **metrics(y[m], p[m]))
                             for n in probs for e, m in evals.items() for s, p in zip(SEEDS, probs[n])])
    per_seed.to_csv(OUT / "metrics_per_seed.csv", index=False)
    g = per_seed.drop(columns="seed").groupby(["eval", "model"], sort=False)
    mean, sd = g.mean(), g.std()
    summary = mean.apply(lambda c: [f"{v:.3f} ± {sd.loc[i, c.name]:.3f}" for i, v in c.items()]).reset_index()

    rows = []
    for e, m in evals.items():
        yy, ref = y[m], y[m] >= 2
        a, b = np.mean(probs["finetuned"], axis=0)[m], np.mean(probs["base"], axis=0)[m]
        pa, pb = a.argmax(1), b.argmax(1)
        lo, hi = boot_ci(len(yy), lambda i: qwk(yy[i], pa[i]) - qwk(yy[i], pb[i]))
        auc_a, auc_b, p_auc = delong(ref, a[:, 2:].sum(1), b[:, 2:].sum(1))
        rows.append(dict(eval=e, images=len(yy), qwk_base=round(qwk(yy, pb), 3), qwk_finetuned=round(qwk(yy, pa), 3),
                         qwk_diff_ci95=f"[{lo:.3f}, {hi:.3f}]", accuracy_diff=round((pa == yy).mean() - (pb == yy).mean(), 3),
                         mcnemar_p=f"{mcnemar(yy, pa, pb):.3g}", auc_diff=round(auc_a - auc_b, 3), delong_p=f"{p_auc:.3g}"))
    tests = pd.DataFrame(rows)
    tests.to_csv(OUT / "significance_tests.csv", index=False)
    text = ["# Fine-tuning on IDRiD (generated by `src/finetune.py`; do not edit)",
            "`base` = EfficientNet-B0 trained on APTOS. `finetuned` = the same checkpoint trained further on 351 IDRiD "
            "images (epoch chosen on 62 IDRiD validation images).", "## Mean ± SD over 3 seeds", md(summary),
            f"## Paired tests on seed-averaged predictions (finetuned minus base, {N_BOOT} bootstrap resamples, "
            "uncorrected p-values)", md(tests)]
    (OUT / "SUMMARY.md").write_text("\n\n".join(text) + "\n", encoding="utf-8")


if __name__ == "__main__":
    train_all()
    report()
    print((OUT / "SUMMARY.md").read_text(encoding="utf-8"))
